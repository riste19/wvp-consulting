/**
 * `/robots.txt`, but host-aware.
 *
 * The site is a static export, so `src/app/robots.ts` bakes exactly ONE
 * robots.txt at build time and every host serves it. That is wrong while the
 * site lives on `*.pages.dev`: the baked file invites crawlers in and points
 * them at a sitemap on a different domain, which is how you end up with the
 * preview and the real site indexed as duplicates of each other.
 *
 * A Function beats a static asset of the same path, so this intercepts the
 * request, and only on a Cloudflare preview host does it answer with a refusal.
 * Anywhere else — the real domain, localhost — it falls through to the baked
 * file, which stays the single source of truth for the real rules.
 *
 * It therefore needs no edit at cutover. Attach the custom domain and the
 * correct behaviour follows from the hostname.
 */

/**
 * Every deployment URL Cloudflare hands out lives under `pages.dev`: the
 * project alias (`wvp-consulting.pages.dev`), per-branch aliases and the
 * per-commit previews. None of them should ever be indexed.
 *
 * Matched on a leading dot so a real domain that merely ends in those letters
 * cannot collide, and `pages.dev` itself is checked separately.
 */
const isCloudflarePreviewHost = (hostname: string) =>
  hostname === "pages.dev" || hostname.endsWith(".pages.dev");

/** No crawling, and no sitemap pointing at the production domain. */
const DISALLOW_ALL = `# This is a Cloudflare preview deployment, not the live site.
# The canonical site is https://wvpconsulting.mk — see its own robots.txt.
User-Agent: *
Disallow: /
`;

export const onRequestGet: PagesFunction = async ({ request, next }) => {
  if (!isCloudflarePreviewHost(new URL(request.url).hostname)) {
    // Serve out/robots.txt, generated by src/app/robots.ts.
    return next();
  }

  return new Response(DISALLOW_ALL, {
    headers: {
      "content-type": "text/plain; charset=utf-8",
      // Crawlers cache robots.txt for up to a day on their own. Keep our own
      // caching short so the rules change promptly at cutover.
      "cache-control": "public, max-age=300",
      // Belt and braces: even a crawler that ignores the body gets told here.
      "x-robots-tag": "noindex, nofollow",
    },
  });
};
